M.normPhone = function(s){
  var d = String(s||'').replace(/[^\d+]/g,'');
  if(d.indexOf('+') === 0) return d;
  if(d.indexOf('0') === 0) return '+972' + d.slice(1);
  return d ? '+972' + d : '';
};
M.prettyPhone = function(s){
  var d = String(s||'').replace(/\D/g,'');
  if(d.length === 12 && d.indexOf('972') === 0) d = '0' + d.slice(3);
  return d.length === 10 ? d.slice(0,3)+'-'+d.slice(3,6)+'-'+d.slice(6) : String(s||'');
};

