    <p class="tell"><b>איך מזהים:</b> קורה תמיד סביב אותו סוג של דבר, ומתחיל בקיפאון קצר לפני הנהמה. <a href="/guide">יש כאן מסלול שאלות שמפרק את זה.</a></p>
